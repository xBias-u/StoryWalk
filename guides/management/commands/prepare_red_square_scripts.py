class Command(BaseCommand):
    help = 'Save the complete short narration set for the Red Square MVP route.'

    def handle(self, *args, **options):
        missing = [title for title in SCRIPTS if not Location.objects.filter(title=title).exists()]
        if missing:
            raise CommandError('Locations are missing: ' + ', '.join(missing))

        with transaction.atomic():
            for title, script in SCRIPTS.items():
                location = Location.objects.get(title=title)
                guide, _ = AudioGuide.objects.get_or_create(location=location)
                guide.short_script = script
                guide.language = 'ru'
                guide.save(update_fields=['short_script', 'language'])
                location.content_status = 'scripted'
                location.is_published = False
                location.editorial_notes = (
                    'Короткий сценарий готов. Перед публикацией нужны полевая проверка перехода '
                    'и озвучка утверждённым голосом.'
                )
                location.save(update_fields=['content_status', 'is_published', 'editorial_notes'])

        self.stdout.write(self.style.SUCCESS(
            f'Short scripts prepared: {len(SCRIPTS)} (audio was not generated)'
        ))
